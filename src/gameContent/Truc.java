package gameContent;

public abstract class Truc {
    private int m_x;
    private int m_y;

    public int get_x() {
        return m_x;
    }

    public void set_x(int m_x) {
        this.m_x = m_x;
    }
    public int get_y() {
        return m_y;
    }
    public void set_y(int m_y) {
        this.m_y = m_y;
    }
}
